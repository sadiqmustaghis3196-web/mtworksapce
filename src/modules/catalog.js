const text = (key, label, required = false, extra = {}) => ({
  key,
  label,
  required,
  ...extra,
});
const ref = (key, label, entity, required = false) =>
  text(key, label, required, { type: "reference", ref: entity });
const select = (key, label, options, required = true) =>
  text(key, label, required, { type: "select", options });
const date = (key, label, required = false) =>
  text(key, label, required, { type: "date" });
const money = (key, label, required = false) =>
  text(key, label, required, { type: "money" });
const number = (key, label, required = false, extra = {}) =>
  text(key, label, required, { type: "number", ...extra });
const note = (key, label, required = false) =>
  text(key, label, required, { type: "textarea" });
const action = (key, label, from, to, extra = {}) => ({
  key,
  label,
  from,
  to,
  ...extra,
});
const reject = (from, to = "Rejected") =>
  action("reject", "Reject", from, to, {
    fields: [note("reason", "Reason", true)],
  });
